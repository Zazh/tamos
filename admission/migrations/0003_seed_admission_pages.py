def seed_admission(apps, schema_editor):
    Region = apps.get_model('regions', 'Region')
    Department = apps.get_model('admission', 'Department')
    GradeGroup = apps.get_model('admission', 'GradeGroup')
    AdmissionPage = apps.get_model('admission', 'AdmissionPage')
    AdmissionIncludedItem = apps.get_model('admission', 'AdmissionIncludedItem')
    AdmissionDocument = apps.get_model('admission', 'AdmissionDocument')
    AdmissionVariant = apps.get_model('admission', 'AdmissionVariant')
    AdmissionTestingFeature = apps.get_model('admission', 'AdmissionTestingFeature')
    AdmissionPricingPlan = apps.get_model('admission', 'AdmissionPricingPlan')

    departments = {d.slug: d for d in Department.objects.all()}
    grades = {g.slug: g for g in GradeGroup.objects.all()}

    page_defaults_with_ru = {
        **PAGE_DEFAULTS,
        **{f'{k}_ru': v for k, v in PAGE_DEFAULTS.items()},
    }

    for region in Region.objects.all():
        page, _ = AdmissionPage.objects.update_or_create(
            region=region,
            defaults=page_defaults_with_ru,
        )

        # Included / documents — общие для всех вариантов
        for order, text in enumerate(INCLUDED_ITEMS, start=1):
            AdmissionIncludedItem.objects.update_or_create(
                page=page, order=order, is_excluded=False,
                defaults={'text': text, 'text_ru': text},
            )
        for order, text in enumerate(DOCUMENT_ITEMS, start=1):
            AdmissionDocument.objects.update_or_create(
                page=page, order=order,
                defaults={'text': text, 'text_ru': text},
            )

        # Варианты
        for dept_slug, grade_slugs in DEPT_GRADES.items():
            department = departments[dept_slug]
            for grade_slug in grade_slugs:
                grade = grades[grade_slug]
                content = _variant_content(dept_slug, grade_slug)
                content_with_ru = {
                    **content,
                    **{f'{k}_ru': v for k, v in content.items()},
                }
                variant, _ = AdmissionVariant.objects.update_or_create(
                    page=page, department=department, grade=grade,
                    defaults=content_with_ru,
                )

                # Inline для grade-1: testing-features + pricing-plans.
                # Для остальных — оставляем пусто (менеджер дозаполняет).
                if grade_slug != '1':
                    continue

                for order, feat in enumerate(TESTING_FEATURES, start=1):
                    AdmissionTestingFeature.objects.update_or_create(
                        variant=variant, order=order,
                        defaults={
                            'icon_svg': feat['icon_svg'],
                            'title': feat['title'],
                            'title_ru': feat['title'],
                            'description': feat['description'],
                            'description_ru': feat['description'],
                        },
                    )
                for order, plan in enumerate(PRICING_PLANS_GRADE_1, start=1):
                    AdmissionPricingPlan.objects.update_or_create(
                        variant=variant, order=order,
                        defaults={
                            'highlight': plan['highlight'],
                            'badge_text': plan['badge_text'],
                            'badge_text_ru': plan['badge_text'],
                            'icon_svg': plan['icon_svg'],
                            'label': plan['label'],
                            'label_ru': plan['label'],
                            'price_value': plan['price_value'],
                            'price_currency': '₸',
                            'note': plan['note'],
                            'note_ru': plan['note'],
                        },
                    )


